public class HashingExample {
    public static void main(String[] args) {
        String java = "Java";
        String python = "Python";
        String cpp = "C++";

        System.out.println("HashCode of Java: " + java.hashCode());
        System.out.println("HashCode of Python: " + python.hashCode());
        System.out.println("HashCode of C++: " + cpp.hashCode());
    }
}
